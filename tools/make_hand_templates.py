"""Build godot/scripts/game/hand_fallback_pose.gd from a recording (tools/rec_read.py format, numpy cache optional).

    python tools/make_hand_templates.py quest_data/recordings/2026-11-17_19-10-07.bin.gz

For each hand, in GRIP-POSE space (the pose the runtime gives a held controller or a hand: the wrist is fixed in it), it
averages the 26 recorded joints over three kinds of tracked frames: OPEN (fingers spread, thumb away), PINCH (thumb tip on
index tip) and FIST (grip squeezed). GodHandVisual blends the three by the trigger and grip values to draw a hand when
no joint data exists (a controller in the hand, or hand tracking lost while the aim/grip pose is still valid).
Also writes the aim pose's offset from the grip pose (used when only the aim pose is valid). Data only: nothing here is a design choice.
"""
import gzip
import json
import struct
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent


def load_array(path):
    raw = (gzip.open if str(path).endswith(".gz") else open)(path, "rb").read()
    n = struct.unpack("<I", raw[8:12])[0]
    ff = json.loads(raw[12:12 + n])["frame_floats"]
    body = raw[12 + n:]
    cnt = len(body) // (ff * 4)
    return np.frombuffer(body[:cnt * ff * 4], dtype="<f4").reshape(cnt, ff)


def qm(q):
    x, y, z, w = q[..., 0], q[..., 1], q[..., 2], q[..., 3]
    r = np.stack([1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w), 2 * (x * y + z * w), 1 - 2 * (x * x + z * z),
                  2 * (y * z - x * w), 2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)], -1)
    return r.reshape(q.shape[:-1] + (3, 3))


def mq(m):
    """3x3 -> quaternion (x, y, z, w), w >= 0."""
    t = np.trace(m)
    if t > 0:
        s = np.sqrt(t + 1) * 2
        q = [(m[2, 1] - m[1, 2]) / s, (m[0, 2] - m[2, 0]) / s, (m[1, 0] - m[0, 1]) / s, s / 4]
    else:
        i = int(np.argmax(np.diag(m)))
        j, k = (i + 1) % 3, (i + 2) % 3
        s = np.sqrt(m[i, i] - m[j, j] - m[k, k] + 1) * 2
        q = [0, 0, 0, 0]
        q[i] = s / 4
        q[j] = (m[j, i] + m[i, j]) / s
        q[k] = (m[k, i] + m[i, k]) / s
        q[3] = (m[k, j] - m[j, k]) / s
    q = np.array(q)
    return q if q[3] >= 0 else -q


def hand_templates(a, side):
    k = 8 if side == "left" else 211
    tr = a[:, k + 20] > 0.5
    ok = (a[:, k + 8] > 0.5) & (a[:, k] > 0.5) & tr
    gp, gq = a[ok, k + 9:k + 12], a[ok, k + 12:k + 16]
    aim_p, aim_q = a[ok, k + 1:k + 4], a[ok, k + 4:k + 8]
    j = a[ok, k + 21:k + 21 + 182].reshape(-1, 26, 7)
    gr = qm(gq)
    rt = np.transpose(gr, (0, 2, 1))
    jp = np.einsum("nij,nmj->nmi", rt, j[..., :3] - gp[:, None, :])  # joint origins in grip space
    jr = np.einsum("nij,nmjk->nmik", rt, qm(j[..., 3:]))  # joint bases in grip space
    pinch = np.linalg.norm(jp[:, 5] - jp[:, 10], axis=1)
    reach = np.linalg.norm(jp[:, [15, 20, 25]] - jp[:, [1]], axis=2).mean(1)  # middle/ring/little tip to wrist
    sel = {
        "open": (pinch > 0.075) & (reach >= np.percentile(reach, 70)),
        "pinch": (pinch < 0.012) & (reach >= np.percentile(reach, 50)),
        "fist": reach <= np.percentile(reach, 10),
    }
    out = {}
    for name, m in sel.items():
        pos = jp[m].mean(0)
        base = mq(jr[m][:, 0].mean(0))  # palm joint basis (mean, re-orthonormalised via SVD)
        u, _, vt = np.linalg.svd(jr[m][:, 0].mean(0))
        base = mq(u @ vt)
        out[name] = (pos, base, int(m.sum()))
    ar = np.einsum("nij,nj->ni", rt, aim_p - gp)
    u, _, vt = np.linalg.svd(np.einsum("nij,njk->nik", rt, qm(aim_q)).mean(0))
    return out, (ar.mean(0), mq(u @ vt)), reach


def fmt_v(v):
    return "Vector3(%.4f, %.4f, %.4f)" % tuple(v)


def main():
    path = sys.argv[1]
    a = load_array(path)
    lines = ["# Generated by tools/make_hand_templates.py from %s. Do not edit by hand." % Path(path).name,
             "extends RefCounted",
             "## Hand poses in GRIP-POSE space (m), recorded on the Quest 3 (see tools/make_hand_templates.py).", ""]
    for side in ("left", "right"):
        t, (aim, aim_q), reach = hand_templates(a, side)
        print(side, {n: (v[2]) for n, v in t.items()}, "aim in grip", aim.round(3), "reach pct", np.percentile(reach, [5, 50, 95]).round(3))
        lines.append("const %s_AIM := %s  # aim pose origin in grip space" % (side.upper(), fmt_v(aim)))
        lines.append("const %s_AIM_Q := Quaternion(%.4f, %.4f, %.4f, %.4f)  # aim pose rotation in grip space" % ((side.upper(),) + tuple(aim_q)))
        for name in ("open", "pinch", "fist"):
            pos, q, n = t[name]
            lines.append("const %s_%s := [  # %d frames" % (side.upper(), name.upper(), n))
            lines.append("\t" + ", ".join(fmt_v(p) for p in pos) + ",")
            lines.append("]")
            lines.append("const %s_%s_PALM := Quaternion(%.4f, %.4f, %.4f, %.4f)" % (side.upper(), name.upper(), *q))
        lines.append("")
    (ROOT / "godot/scripts/game/hand_fallback_pose.gd").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
